"""Differential gate: the head must refuse everything main refuses.

tests/fixtures/main_verdicts.json holds main's verdicts for the corpus in
diff_corpus.py (generated by gen_main_verdicts.py from a pristine main
checkout). A command main refuses and the head allows is a regression unless it
is listed in `allowed_changes` with a reason.
"""
import hashlib
import importlib.util
import json
import os
import sys
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import diff_corpus  # noqa: E402

spec = importlib.util.spec_from_file_location('differential_guard', HERE.parent / 'guard.py')
guard = importlib.util.module_from_spec(spec)
spec.loader.exec_module(guard)

FIXTURE = json.loads((HERE / 'fixtures' / 'main_verdicts.json').read_text())


@pytest.fixture(autouse=True)
def synthetic_home(monkeypatch):
    monkeypatch.setenv('HOME', diff_corpus.HOME_PARENT)
    monkeypatch.setenv('HERMES_HOME', diff_corpus.HOME_PARENT + '/.hermes')


def _verdicts():
    commands = diff_corpus.corpus()
    return commands, {c: bool(guard.check_shell(c, cwd=diff_corpus.HOME_PARENT)) for c in commands}


def test_fixture_matches_corpus():
    commands = diff_corpus.corpus()
    assert len(commands) == FIXTURE['corpus_size']
    digest = hashlib.sha256('\0'.join(commands).encode()).hexdigest()
    assert digest == FIXTURE['corpus_sha256'], 'corpus changed: rerun gen_main_verdicts.py against main'


def test_no_new_false_negatives_against_main():
    commands, head = _verdicts()
    allowed = FIXTURE['allowed_changes']
    regressions = [c for c in FIXTURE['refused_by_main'] if not head[c] and c not in allowed]
    assert not regressions, f'{len(regressions)} commands main refuses but head allows, e.g. {regressions[:5]}'
    assert all(allowed.values()), 'every allowed change needs a reason'
    for command in allowed:
        assert command in FIXTURE['refused_by_main'] and not head[command], 'stale allowed_changes entry'


@pytest.mark.parametrize('command', diff_corpus.REVIEW_REPROS)
def test_every_review_repro_is_refused(command):
    assert guard.check_shell(command, cwd=diff_corpus.HOME_PARENT)


def test_counts_report():
    commands, head = _verdicts()
    refused_main = set(FIXTURE['refused_by_main'])
    refused_head = {c for c in commands if head[c]}
    newly_allowed = refused_main - refused_head
    print(f'corpus={len(commands)} refused_by_main={len(refused_main)} '
          f'refused_by_head={len(refused_head)} newly_allowed_by_head={len(newly_allowed)}')
    assert len(newly_allowed) == len(FIXTURE['allowed_changes'])
