"""Least-privilege boundary artifacts: probe key line, polkit grant, install checks.

Pure functions; installation scripts call them, nothing here touches the host.
"""
import json
import os
import re
import stat

BROKER_USER = 'hermes-runners-broker'
_SAFE_PATH = re.compile(r'/(usr|opt)/[A-Za-z0-9_./-]{1,200}')


def probe_authorized_key(public_key, interpreter, script):
    """Forced-command line for the read-only probe identity (plan §5)."""
    for path in (interpreter, script):
        if not isinstance(path, str) or not _SAFE_PATH.fullmatch(path) or '..' in path:
            raise ValueError('unsafe_probe_path')
    parts = public_key.split()
    if len(parts) < 2 or parts[0] not in ('ssh-ed25519', 'ecdsa-sha2-nistp256') or not re.fullmatch(r'[A-Za-z0-9+/=]+', parts[1]):
        raise ValueError('invalid_public_key')
    return 'restrict,command="%s -I %s" %s %s hermes-read-only-probe' % (interpreter, script, parts[0], parts[1])


def polkit_rule(policy, *, broker_user=BROKER_USER):
    """Grant the broker identity only `start` of policy-listed canary units."""
    if not re.fullmatch(r'[a-z_][a-z0-9_-]{0,31}', broker_user):
        raise ValueError('invalid_user')
    units = sorted(t['unit'] for t in policy['targets'] if t['canary'] and 'service_start' in t['operations'])
    header = ('// Generated by the Hermes runners broker installer from broker policy.\n'
              '// Grants %s only the start verb on exactly listed canary units.\n' % broker_user)
    if not units:
        return header + '// No canary units are listed: this rule grants nothing.\n'
    match = ' || '.join('unit == %s' % json.dumps(u) for u in units)
    return header + (
        'polkit.addRule(function(action, subject) {\n'
        '    if (action.id == "org.freedesktop.systemd1.manage-units" && subject.user == %s) {\n'
        '        var unit = action.lookup("unit");\n'
        '        var verb = action.lookup("verb");\n'
        '        if (verb == "start" && (%s)) {\n'
        '            return polkit.Result.YES;\n'
        '        }\n'
        '    }\n'
        '});\n') % (json.dumps(broker_user), match)


def _mode(st):
    return stat.S_IMODE(st.st_mode)


def boundary_problems(*, code_dir, policy_path, credential_dir, broker_uid, agent_uid):
    """List reasons the agent user could alter broker code/policy or read credentials."""
    problems = []
    for dirpath, dirs, files in os.walk(code_dir):
        for name in [dirpath] + [os.path.join(dirpath, f) for f in files]:
            st = os.lstat(name)
            if st.st_uid != 0:
                problems.append('code not root-owned: ' + name)
            if _mode(st) & 0o022:
                problems.append('code group/world writable: ' + name)
    st = os.lstat(policy_path)
    if stat.S_ISLNK(st.st_mode) or not stat.S_ISREG(st.st_mode):
        problems.append('policy not a regular file')
    if st.st_uid != 0:
        problems.append('policy not root-owned')
    if _mode(st) & 0o022:
        problems.append('policy group/world writable')
    st = os.lstat(credential_dir)
    if st.st_uid != broker_uid or _mode(st) & 0o077:
        problems.append('credentials directory not private to broker')
    for name in os.listdir(credential_dir):
        fst = os.lstat(os.path.join(credential_dir, name))
        if stat.S_ISREG(fst.st_mode) and (fst.st_uid != broker_uid or _mode(fst) & 0o077):
            problems.append('credential readable beyond broker: ' + name)
    if agent_uid == broker_uid:
        problems.append('broker identity equals agent identity')
    return problems
